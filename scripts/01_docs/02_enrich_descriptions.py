"""
Enrich docs/descriptions.yaml with LLM-generated table metadata.

For every table in docs/tables/*.md whose entry is MISSING or STALE in
docs/descriptions.yaml, ask a local LLM (LM Studio, OpenAI-compatible server)
to describe the table. The answer must be valid JSON; it is validated before
being merged into descriptions.yaml.

Staleness: entries generated by this script store a `columns_snapshot`. If the
table's current column list differs (column added/removed/renamed), the entry
is regenerated. Entries without a snapshot are kept unless their description
references a column that no longer exists (backticks) or `--force` is used.
Use `--force` to regenerate every table regardless, or `--views` to rebuild
only the AW view objects (v* naming).

Hand-edited entries are protected: an entry whose `source` is "human" is NEVER
overwritten (not by `--force`, not by `--views`, not by a schema-drift rebuild).
Pass `--force-human` to let the LLM replace them too.

Entry format written for each new table:
    "<Schema>.<Table>":
        description: "..."
        domain: "..."
        keywords: [...]
        questions: ["..."]
        source: llm          # switch to "human" when edited by hand
        model: <model name>

Usage:
    python scripts/01_docs/02_enrich_descriptions.py
    python scripts/01_docs/02_enrich_descriptions.py --limit 5
    python scripts/01_docs/02_enrich_descriptions.py --force --limit 3
    python scripts/01_docs/02_enrich_descriptions.py --force-human   # override human entries too
"""

import json
import re
import sys
import time
import urllib.error
import urllib.request
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[2]
DOCS_DIR = ROOT / "docs"
OUT_DIR = DOCS_DIR / "tables"
DESCRIPTIONS_FILE = DOCS_DIR / "descriptions.yaml"

LLM_URL = "http://127.0.0.1:1234/v1/chat/completions"
LLM_MODEL = "google/gemma-4-e4b"
ATTEMPTS = 3
TIMEOUT = 300

