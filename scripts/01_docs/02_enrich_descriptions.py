def validate(entry, allowed_names):
    errors = []
    if len(entry.get("questions", [])) != 3:
        errors.append("need exactly 3 questions")
    if len(entry.get("keywords", [])) < 8:
        errors.append("need at least 8 keywords")
    if not entry.get("domain"):
        errors.append("missing domain")
    for name in re.findall(r"`([^`]+)`", entry.get("description", "")):
        if name not in allowed_names:
            errors.append(f"unknown name: {name}")
    return errors


def load_existing() -> dict:
    if not DESCRIPTIONS_FILE.exists():
        return {}
    with open(DESCRIPTIONS_FILE, encoding="utf-8") as fh:
        return yaml.safe_load(fh) or {}


def parse_table_md(path: Path) -> dict:
    text = path.read_text(encoding="utf-8")
    body = text
    meta = {}
    if text.startswith("---"):
        parts = text.split("---", 2)
        meta = yaml.safe_load(parts[1]) or {}
        body = parts[2]

    desc_match = re.search(r"^# .+?\n\n(.*?)(?=\n## )", body, re.S)
    description = desc_match.group(1).strip() if desc_match else ""

    cols_section = body
    cols_start = body.find("## Columns")
    if cols_start != -1:
        next_heading = body.find("\n## ", cols_start + len("## Columns"))
        cols_section = body[cols_start + len("## Columns"):next_heading] if next_heading != -1 else body[cols_start:]

    columns = [
        (name, dtype)
        for name, dtype in re.findall(r"\|\s*`(.+?)`\s*\|\s*([^|]+?)\s*\|", cols_section)
    ][:30]

    relationships = re.findall(r"- `([^`]+)` -> `([^`]+)`", body)

    return {
        "name": meta.get("table") or path.stem,
        "kind": meta.get("kind"),
        "rows": meta.get("rows"),
        "description": description,
        "columns": columns,
        "relationships": relationships,
    }


def build_prompt(table: dict) -> str:
    lines = [
        f"table: {table['name']}",
        f"rows: {table['rows']}" if table["rows"] is not None else "rows: n/a",
    ]
    if table["kind"] == "view":
        lines.append(
            "kind: VIEW (a read-only projection over one or more base tables, "
            "not a physical table — say so explicitly in the description, "
            "e.g. 'A read-only view over ...')"
        )
    if table["columns"]:
        lines.append("columns (name: type):")
        lines.extend(f"- {name}: {dtype}" for name, dtype in table["columns"])
    if table["relationships"]:
        lines.append("relationships:")
        lines.extend(f"- {col} -> {ref}" for col, ref in table["relationships"])
    return "\n".join(lines)


def extract_json(text: str) -> dict:
    text = text.strip()
    fence = re.match(r"^```(?:json)?\s*(.*?)\s*```$", text, re.S)
    if fence:
        text = fence.group(1)
    try:
        return json.loads(text)
    except (ValueError, TypeError):
        pass
    start, end = text.find("{"), text.rfind("}")
    if start != -1 and end > start:
        try:
            return json.loads(text[start:end + 1])
        except (ValueError, TypeError):
            pass
    raise ValueError("model output is not a valid JSON object")


def is_valid(obj) -> bool:
    if not isinstance(obj, dict):
        return False
    desc, domain = obj.get("description"), obj.get("domain")
    keywords, questions = obj.get("keywords"), obj.get("questions")
    return (
        isinstance(desc, str) and len(desc.strip()) >= 5
        and isinstance(domain, str) and len(domain.strip()) >= 1
        and isinstance(keywords, list)
        and all(isinstance(k, str) and k.strip() for k in keywords)
        and isinstance(questions, list)
        and all(isinstance(q, str) and q.strip() for q in questions)
    )


def call_llm(prompt: str) -> str:
    payload = {
        "model": LLM_MODEL,
        "messages": [
            {"role": "system", "content": SYSTEM_PROMPT},
            {"role": "user", "content": prompt},
        ],
        "temperature": 0.2,
        "max_tokens": 512,
        "reasoning_effort": "none",
    }
    req = urllib.request.Request(
        LLM_URL,
        data=json.dumps(payload).encode("utf-8"),
        headers={"Content-Type": "application/json"},
    )
    with urllib.request.urlopen(req, timeout=TIMEOUT) as resp:
        data = json.loads(resp.read().decode("utf-8"))
    return data["choices"][0]["message"]["content"]


def generate_entry(prompt: str, existing_columns: dict | None, allowed_names: set,
                   current_cols: list[str]) -> dict:
    """Call the LLM (with retries incl. transient HTTP errors) and validate the JSON answer."""
    last_error = ""
    for attempt in range(1, ATTEMPTS + 1):
        try:
            content = call_llm(prompt)
            obj = extract_json(content)
            if not is_valid(obj):
                last_error = "invalid JSON structure"
                continue
            errors = validate(obj, allowed_names)
            if errors:
                last_error = "; ".join(errors)
                continue
            entry = {
                "description": obj["description"].strip(),
                "domain": obj["domain"].strip(),
                "keywords": [k.strip() for k in obj["keywords"]],
                "questions": [q.strip() for q in obj["questions"]],
                "source": "llm",
                "model": LLM_MODEL,
                "columns_snapshot": current_cols,
            }
            if existing_columns:
                entry["columns"] = existing_columns
            return entry
        except (
            ValueError, KeyError, TypeError,
            urllib.error.HTTPError, urllib.error.URLError,
            ConnectionError, TimeoutError, OSError,
        ) as exc:
            last_error = str(exc) or type(exc).__name__
            time.sleep(2)
    raise RuntimeError(f"LLM did not produce valid JSON after {ATTEMPTS} attempts ({last_error})")


def save_descriptions(data: dict) -> None:
    header = (
        "# Human-readable metadata for AdventureWorks tables.\n"
        "#   description: what the table holds (one row = ?)\n"
        "#   domain: sales / production / purchasing / human-resources / person\n"
        "#   keywords / questions: RAG search + QA helpers\n"
        "#   source: 'llm' (auto-generated) -> change to 'human' when corrected\n"
        "# Entries are merged into each table's generated .md file.\n"
    )
    with open(DESCRIPTIONS_FILE, "w", encoding="utf-8") as fh:
        fh.write(header)
        fh.write(
            yaml.safe_dump(data, sort_keys=False, allow_unicode=True, default_flow_style=False)
        )


def is_human(meta: dict) -> bool:
    """True for entries a human edited by hand (source: human). Those are never
    replaced by the LLM unless --force-human is given."""
    return str(meta.get("source") or "").strip().lower() == "human"


def schema_drift(meta: dict, table: dict, current_cols: list[str], force: bool = False) -> str | None:
    """Return a reason string if the stored entry is stale vs the current schema, else None."""
    if force:
        return "forced"
    snapshot = meta.get("columns_snapshot")
    if isinstance(snapshot, list) and sorted(snapshot) != current_cols:
        return "schema change"
    known = set(current_cols) | {table["name"]}
    for name in re.findall(r"`([^`]+)`", str(meta.get("description", ""))):
        if name not in known:
            return f"stale reference to missing column `{name}`"
    return None


def parse_kind(path: Path) -> str:
    text = path.read_text(encoding="utf-8")
    if text.startswith("---"):
        meta = yaml.safe_load(text.split("---", 2)[1]) or {}
        return str(meta.get("kind") or "")
    return ""


def main() -> int:
    args = [a for a in sys.argv[1:]]
    only_table = None
    limit = None
    force = "--force" in args
    views_only = "--views" in args
    force_human = "--force-human" in args
    args = [a for a in args if a not in ("--force", "--views", "--force-human")]
    if args and not args[0].startswith("--"):
        only_table = args[0]
    if "--limit" in args:
        limit = int(args[args.index("--limit") + 1])

    existing = load_existing()
    files = sorted(OUT_DIR.glob("*.md"))
    if only_table:
        files = [p for p in files if p.stem == only_table]
    if views_only:
        files = [p for p in files if parse_kind(p) == "view"]
    if limit:
        files = files[:limit]
    if not files:
        print(f"ERROR: no .md files found in {OUT_DIR}. Run scripts/01_docs/01_generate_table_docs.py first.")
        return 1

    skipped, added, failed, rebuilt, human = 0, 0, 0, 0, 0
    output = dict(existing)

    for path in files:
        key = path.stem
        meta = existing.get(key)
        table = parse_table_md(path)
        current_cols = sorted(c[0] for c in table["columns"])

        if isinstance(meta, dict) and meta.get("description"):
            if is_human(meta) and not force_human:
                human += 1
                skipped += 1
                print(f"  * {key}: SKIP (source=human, hand-edited; --force-human to override)", flush=True)
                continue
            drift_reason = schema_drift(meta, table, current_cols, force=force or views_only)
            if drift_reason is None:
                skipped += 1
                continue
            print(f"  * {key}: REBUILD ({drift_reason}) ...", flush=True)
            rebuilt += 1
        else:
            print(f"  * {key}: querying {LLM_MODEL} ...", flush=True)

        existing_columns = meta.get("columns") if isinstance(meta, dict) else None
        allowed_names = {key, table["name"]} | set(current_cols)
        try:
            entry = generate_entry(build_prompt(table), existing_columns, allowed_names, current_cols)
        except (RuntimeError, urllib.error.URLError, ConnectionError, TimeoutError, OSError) as exc:
            failed += 1
            print(f"    FAIL: {exc}", flush=True)
            continue

        output[key] = entry
        added += 1
        print(f"    OK: {entry['description'][:80]}", flush=True)
        save_descriptions(output)

    if output:
        save_descriptions(output)
        print(f"\nWrote {DESCRIPTIONS_FILE}")

    print(f"\nSummary: {skipped} already described ({human} hand-edited, kept), "
          f"{rebuilt} rebuilt (schema drift/force), {added} added, {failed} failed.")
    return 1 if failed else 0


if __name__ == "__main__":
    sys.exit(main())